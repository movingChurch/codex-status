var renderColors = map[string]string{"model": "\x1b[0;1;38;2;58;207;137m", "mint": "\x1b[0;38;2;0;181;113m", "blue": "\x1b[0;38;2;72;166;255m", "yellow": "\x1b[0;38;2;229;194;38m", "dim": "\x1b[0;38;2;161;165;167m", "label": "\x1b[0;38;2;62;67;69m"}
var renderOSC = regexp.MustCompile("\x1b\\][^\x07\x1b]*(?:\x07|\x1b\\\\|$)")
var renderCSI = regexp.MustCompile("\x1b\\[[0-?]*[ -/]*[@-~]")
var renderUUID = regexp.MustCompile(`^[0-9a-fA-F]{32}$`)

type renderSegment struct {
	text, tint string
	target     any
}

func renderPart(text, tint string) renderSegment { return renderSegment{text, tint, nil} }
func renderClean(v any) string {
	s, ok := v.(string)
	if !ok {
		return "—"
	}
	r := []rune(s)
	if len(r) > 4096 {
		s = string(r[:4096])
	}
	s = renderCSI.ReplaceAllString(renderOSC.ReplaceAllString(s, ""), "")
	return strings.Map(func(r rune) rune {
		if renderInRanges(r, renderControlRanges) {
			return -1
		}
		return r
	}, s)
}
func renderInRanges(r rune, ranges [][2]rune) bool {
	low, high := 0, len(ranges)
	for low < high {
		mid := (low + high) / 2
		if r < ranges[mid][0] {
			high = mid
		} else if r > ranges[mid][1] {
			low = mid + 1
		} else {
			return true
		}
	}
	return false
}
func renderCell(r rune) int {
	if renderInRanges(r, renderCombiningRanges) {
		return 0
	}
	if renderInRanges(r, renderWideRanges) {
		return 2
	}
	return 1
}

func renderTextWidth(s string) int {
	n := 0
	for _, r := range s {
		n += renderCell(r)
	}
	return n
}
func renderWidth(parts []renderSegment) int {
	n := 0
	for _, p := range parts {
		n += renderTextWidth(renderClean(p.text))
	}
	return n
}
func renderURL(v any) string {
	s, ok := v.(string)
	if !ok || s == "" || len([]rune(s)) > 4096 || linkControl(s) {
		return ""
	}
	for _, r := range s {
		if unicode.IsSpace(r) || r == '\\' {
			return ""
		}
	}
	u, err := url.Parse(s)
	if err != nil || u.User != nil {
		return ""
	}
	if strings.HasPrefix(s, "https://") && u.Hostname() != "" {
		if u.Port() != "" {
			p, e := strconv.Atoi(u.Port())
			if e != nil || p <= 0 || p > 65535 {
				return ""
			}
		}
		return s
	}
	if strings.HasPrefix(s, "file://") && (u.Host == "" || u.Host == "localhost") && strings.HasPrefix(u.Path, "/") {
		return s
	}
	return ""
}
func renderLine(parts []renderSegment, width int, color bool) string {
	var out strings.Builder
	used := 0
	for _, p := range parts {
		var chunk strings.Builder
		for _, r := range renderClean(p.text) {
			size := renderCell(r)
			if used+size > width {
				break
			}
			if size == 0 && used == 0 {
				continue
			}
			chunk.WriteRune(r)
			used += size
		}
		if chunk.Len() > 0 {
			target := ""
			if color {
				out.WriteString(renderColors[p.tint])
				target = renderURL(p.target)
			}
			if target != "" {
				out.WriteString("\x1b]8;;" + target + "\x1b\\")
			}
			out.WriteString(chunk.String())
			if target != "" {
				out.WriteString("\x1b]8;;\x1b\\")
			}
		}
		if used >= width {
			break
		}
	}
	if color && out.Len() > 0 {
		out.WriteString("\x1b[0m")
	}
	return out.String()
}
func renderNumber(v any) (float64, bool) {
	var n float64
	switch x := v.(type) {
	case int:
		n = float64(x)
	case int64:
		n = float64(x)
	case int32:
		n = float64(x)
	case uint64:
		n = float64(x)
	case float64:
		n = x
	case float32:
		n = float64(x)
	case json.Number:
		var err error
		n, err = x.Float64()
		if err != nil {
			return 0, false
		}
	default:
		return 0, false
	}
	return n, !math.IsNaN(n) && !math.IsInf(n, 0)
}
func renderUsed(v any) (float64, bool) {
	n, ok := renderNumber(v)
	return 100 - n, ok && n >= 0 && n <= 100
}
func renderTokens(v any) (float64, bool) {
	n, ok := renderNumber(v)
	return n, ok && n >= 0 && n <= 1e12 && n == math.Trunc(n)
}
func renderFormatTokens(n float64) string {
	if n >= 1000 {
		return fmt.Sprintf("%.0fk", math.Floor(n/1000+0.5))
	}
	return fmt.Sprintf("%.0f", n)
}
func renderDuration(v any) string {
	n, ok := renderNumber(v)
	if !ok || n < 0 || n > 1e10 {
		return "—"
	}
	sec := int64(n)
	if sec >= 3600 {
		return fmt.Sprintf("%d:%02d:%02d", sec/3600, sec%3600/60, sec%60)
	}
	return fmt.Sprintf("%d:%02d", sec/60, sec%60)
}
func renderTimestamp(v any) (float64, bool) {
	if n, ok := renderNumber(v); ok {
		return n, true
	}
	if s, ok := v.(string); ok {
		for _, layout := range []string{time.RFC3339Nano, "2006-01-02 15:04:05Z07:00"} {
			if t, e := time.Parse(layout, s); e == nil {
				return float64(t.Unix()) + float64(t.Nanosecond())/1e9, true
			}
		}
	}
	return 0, false
}
func renderSlider(n float64) string {
	filled := int(math.Floor(n/10 + 0.5))
	return strings.Repeat("▓", filled) + strings.Repeat("░", 10-filled)
}
func renderCountdown(v any, now float64) string {
	n, ok := renderTimestamp(v)
	if !ok {
		return ""
	}
	delta := n - now
	if delta <= 0 {
		return "reset pending"
	}
	minutes := int64(math.Floor(delta / 60))
	if minutes < 1 {
		return "<1m"
	}
	parts := []string{}
	if d := minutes / 1440; d > 0 {
		parts = append(parts, fmt.Sprintf("%dd", d))
	}
	if h := minutes % 1440 / 60; h > 0 {
		parts = append(parts, fmt.Sprintf("%dhr", h))
	}
	if m := minutes % 60; m > 0 {
		parts = append(parts, fmt.Sprintf("%dm", m))
	}
	return strings.Join(parts, " ")
}
func renderCapacity(s map[string]any, width int, now float64) []renderSegment {
	context, known := renderUsed(s["context_remaining"])
	used, uok := renderTokens(s["context_used"])
	window, wok := renderTokens(s["context_window"])
	var parts []renderSegment
	for _, mode := range [][3]bool{{true, true, true}, {true, true, false}, {false, true, false}, {false, false, false}} {
		bars, counts, timers := mode[0], mode[1], mode[2]
		label := "Context"
		if !bars && !counts {
			label = "Ctx"
		}
		value := "n/a"
		if !known {
			switch s["context_status"] {
			case "pending":
				value = "pending"
			case "unavailable":
				value = "unavailable"
			case "error":
				value = "read failed"
			case "stale":
				value = "stale"
			}
		}
		if known {
			value = fmt.Sprintf("%.0f%%", math.Floor(context+0.5))
		}
		if counts && uok && wok && window > 0 {
			value = renderFormatTokens(used) + "/" + renderFormatTokens(window) + " (" + value + ")"
		}
		if bars && known {
			value = renderSlider(context) + " " + value
		}
		parts = []renderSegment{renderPart(label+" ", "label"), renderPart(value, "mint")}
		observed := false
		for _, q := range [][3]string{{"five_hour", "5H", "blue"}, {"weekly", "7D", "yellow"}} {
			quota, _ := s[q[0]].(map[string]any)
			if quota == nil {
				continue
			}
			observed = true
			n, ok := renderUsed(quota["remaining"])
			value = "n/a"
			if ok {
				value = fmt.Sprintf("%.1f%%", n)
			}
			if bars && ok {
				value = renderSlider(n) + " " + value
			}
			parts = append(parts, renderPart(" │ ", "label"), renderSegment{q[1], "label", s["usage_url"]}, renderPart(" ", "label"), renderPart(value, q[2]))
			if timers && ok {
				if countdown := renderCountdown(quota["resets_at"], now); countdown != "" {
					parts = append(parts, renderPart(" ↻ ", "label"), renderSegment{countdown, "dim", s["usage_url"]})
				}
			}
		}
		if !observed {
			parts = append(parts, renderPart(" │ Limits pending", "dim"))
		}
		if pools, ok := s["quota_pools"].([]any); ok {
			for _, p := range pools {
				q, _ := p.(map[string]any)
				n, ok := renderUsed(q["remaining"])
				if !ok {
					continue
				}
				label := renderClean(q["label"])
				parts = append(parts, renderPart(" │ "+label+" ", "label"), renderPart(fmt.Sprintf("%.1f%%", n), "yellow"))
				if timers {
					if countdown := renderCountdown(q["resets_at"], now); countdown != "" {
						parts = append(parts, renderPart(" ↻ "+countdown, "dim"))
					}
				}
			}
			if len(pools) > 0 && !observed { // Replace aggregate placeholder when pools are present.
				filtered := parts[:0]
				for _, part := range parts {
					if part.text != " │ Limits pending" {
						filtered = append(filtered, part)
					}
				}
				parts = filtered
			}
		}
		if renderWidth(parts) <= width {
			return parts
		}
	}
	return parts
}
func renderAppend(parts []renderSegment, addition []renderSegment, width int) []renderSegment {
	if renderWidth(parts)+renderWidth(addition) <= width {
		return append(parts, addition...)
	}
	return parts
}
func renderBound(v any) bool {
	s, ok := v.(string)
	if !ok {
		return false
	}
	s = strings.TrimPrefix(s, "urn:uuid:")
	s = strings.Trim(s, "{}")
	return renderUUID.MatchString(strings.ReplaceAll(s, "-", ""))
}
func renderActivity(s map[string]any, width int, now float64) []renderSegment {
	key := renderClean(s["state"])
	state := map[string]string{"ready": "Ready", "pending": "Connecting", "live": "Connected", "stale": "Stale", "account-changed": "Account changed", "error": "Read failed", "ended": "Ended", "hidden": "Hidden"}[key]
	if state == "" {
		state = "Pending"
	}
	if key == "live" && !renderBound(s["session_id"]) && ((s["runtime"] != "claude" && s["runtime"] != "antigravity") || renderClean(s["session_id"]) == "") {
		state = "Connecting"
	}
	activity := map[string]string{"waiting": "Waiting", "working": "Working", "complete": "Complete", "interrupted": "Interrupted"}[renderClean(s["activity"])]
	if activity == "" {
		activity = "Unknown"
	}
	reason := ""
	if renderClean(s["quota_scope"]) == "unsupported" {
		reason = " · Unsupported quota"
	}
	text := state + reason + " · " + activity
	if issue := map[string]string{"ambiguous-root": "Session ambiguous", "unsupported-root": "Incompatible session data", "resume-mismatch": "Resume mismatch", "inspection-failed": "Process inspection unavailable", "process-mismatch": "Process changed", "invalid-session": "Invalid session", "invalid-path": "Invalid path", "process-ended": "Session ended"}[renderClean(s["binding_reason"])]; issue != "" {
		text = state + " · " + issue
	}
	if key == "ready" {
		text = "Ready · Send a message to start session tracking"
	}
	parts := []renderSegment{renderPart(text, "dim")}
	if err, ok := s["quota_error"].(string); ok && err != "" {
		if !renderMember(err, "rate-limited timeout unavailable not-authenticated account-changed no-credentials unsupported api-error parse-error read-failed") {
			err = "unavailable"
		}
		parts = renderAppend(parts, []renderSegment{renderPart(" │ Quota "+err, "dim")}, width)
	}
	if key != "ready" && s["elapsed"] != nil {
		parts = renderAppend(parts, []renderSegment{renderPart(" │ Elapsed ", "label"), {renderDuration(s["elapsed"]), "dim", s["session_url"]}}, width)
	}
	cached, cok := renderTokens(s["cached_tokens"])
	inputs, iok := renderTokens(s["input_tokens"])
	if cok && iok && cached <= inputs {
		addition := []renderSegment{renderPart(" │ Cached ", "label"), renderPart(renderFormatTokens(cached), "dim")}
		if inputs > 0 {
			addition = append(addition, renderPart(" Hit rate ", "label"), renderPart(fmt.Sprintf("%.1f%%", cached/inputs*100), "dim"))
		}
		parts = renderAppend(parts, addition, width)
	}
	tool, _ := s["tool"].(string)
	if tool != "" && renderMember(tool, "exec_command write_stdin apply_patch shell shell_command") {
		parts = renderAppend(parts, []renderSegment{renderPart(" │ "+tool, "blue")}, width)
	}
	if observed, ok := renderTimestamp(s["quota_updated_at"]); ok && observed >= -62135596800 && observed <= 253402300799 {
		stamp := time.Unix(int64(observed), 0).Local().Format("01/02 15:04:05")
		parts = renderAppend(parts, []renderSegment{renderPart(" │ Quota observed ", "dim"), {stamp, "dim", s["usage_url"]}, renderPart(" ("+renderDuration(math.Max(0, now-observed))+" ago)", "dim")}, width)
	}
	return parts
}

// Render returns three cell-bounded rows and emits trusted OSC 8 links only in color mode.
func Render(snapshot map[string]any, width int, color bool) []string {
	if width < 1 {
		width = 1
	}
	if width > 500 {
		width = 500
	}
	model := renderClean(snapshot["model"])
	if model == "" || model == "—" {
		model = "Codex"
		if snapshot["runtime"] == "claude" {
			model = "Claude Code"
		}
		if snapshot["runtime"] == "antigravity" {
			model = "Antigravity"
		}
	}
	first := []renderSegment{renderPart(model, "model")}
	effort := renderClean(snapshot["effort"])
	if effort != "" && effort != "—" {
		first = append(first, renderPart(" Effort ", "label"), renderPart(effort, "mint"))
	}
	cwd := renderClean(snapshot["cwd"])
	if width >= 65 && cwd != "" && cwd != "—" {
		pieces := strings.Split(strings.TrimRight(cwd, "/"), "/")
		if len(pieces) > 2 {
			pieces = pieces[len(pieces)-2:]
		}
		location := strings.Join(pieces, "/")
		if location == "" {
			location = "/"
		}
		first = append(first, renderPart(" │ Directory ", "label"), renderSegment{location, "dim", snapshot["directory_url"]})
	}
	branch := renderClean(snapshot["branch"])
	if width >= 50 && branch != "" && branch != "—" {
		first = append(first, renderPart(" Branch ", "label"), renderSegment{renderLine([]renderSegment{renderPart(branch, "mint")}, 26, false), "mint", snapshot["branch_url"]})
	}
	now := float64(time.Now().UnixNano()) / 1e9
	return []string{renderLine(first, width, color), renderLine(renderCapacity(snapshot, width, now), width, color), renderLine(renderActivity(snapshot, width, now), width, color)}
}

